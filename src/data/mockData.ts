export const getDemoStudentsForLevels = (activeLevels: EducationalLevel[] = ['secundaria']): Student[] => {
  const isOnlySecundaria = activeLevels.length === 1 && activeLevels[0] === 'secundaria';
  const isOnlyPrimaria = activeLevels.length === 1 && activeLevels[0] === 'primaria';
  
  if (isOnlySecundaria) {
    return DEMO_STUDENTS_SECUNDARIA;
  }
  if (isOnlyPrimaria) {
    return DEMO_STUDENTS_PRIMARIA;
  }
  
  // Multinivel / Integral: Combine Primaria, Secundaria and Inicial
  return [
    ...DEMO_STUDENTS_SECUNDARIA.slice(0, 4),
    ...DEMO_STUDENTS_PRIMARIA.slice(0, 4),
    INITIAL_STUDENTS[INITIAL_STUDENTS.length - 1], // Thiago Inicial 5 años
  ];
};

